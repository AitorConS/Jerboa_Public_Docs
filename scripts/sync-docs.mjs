import { readFile, writeFile, readdir, mkdir, unlink, access } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = path.resolve(process.env.JERBOA_SOURCE || path.join(root, '../jerboa'));
const destination = path.join(root, 'src/pages');
const check = process.argv.includes('--check');
const optional = process.argv.includes('--if-present');
const marker = '<!-- Generated by scripts/sync-docs.mjs. Edit jerboa/docs instead. -->';
const lastmodPath = path.join(root, 'src/data/lastmod.json');

function escapeAttr(value) {
  return value.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
}

function warnMissingAlt(file, body) {
  const stripped = body.replace(/```[\s\S]*?```/g, '');
  for (const match of stripped.matchAll(/!\[([^\]]*)\]\(([^)\s]+)\)/g)) {
    if (!match[1].trim()) console.warn(`Image missing alt text: ${file} (${match[2]})`);
  }
  for (const match of stripped.matchAll(/<img\b([^>]*?)\/?>/gi)) {
    const alt = match[1].match(/\balt\s*=\s*(?:"([^"]*)"|'([^']*)')/i);
    const value = alt ? (alt[1] ?? alt[2]) : '';
    if (!value.trim()) {
      const src = match[1].match(/\bsrc\s*=\s*(?:"([^"]*)"|'([^']*)')/i);
      console.warn(`Image missing alt text: ${file} (${src?.[1] || src?.[2] || 'unknown'})`);
    }
  }
}

// lastmod is the day a page's published text last changed, recorded here
// when the sync writes it. Git history cannot give it: the docs-sync workflow
// checks the engine out at depth 1, so every file would carry the tip commit.
async function updateLastmod(changedSlugs, slugs) {
  const previous = JSON.parse(await readFile(lastmodPath, 'utf8').catch(() => '{}'));
  const today = new Date().toISOString().slice(0, 10);
  const next = {};
  for (const slug of [...slugs].sort()) next[slug] = changedSlugs.has(slug) || !previous[slug] ? today : previous[slug];
  const content = `${JSON.stringify(next, null, 2)}\n`;
  if (JSON.stringify(previous, null, 2) + '\n' !== content) await writeFile(lastmodPath, content);
}

try {
  await access(path.join(source, 'docs'));
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
  if (!optional || process.env.JERBOA_SOURCE) throw new Error(`Jerboa source missing: ${source}. Set JERBOA_SOURCE to its checkout.`);
  await access(path.join(destination, 'getting-started.md'));
  console.log('Jerboa checkout absent; using the committed documentation snapshot.');
  process.exit(0);
}

const versions = {
  cli: (await readFile(path.join(source, 'VERSION.md'), 'utf8')).trim(),
  kernel: (await readFile(path.join(source, 'kernel/VERSION'), 'utf8')).trim(),
};
const files = (await readdir(path.join(source, 'docs'))).filter(name => name.endsWith('.md')).sort();
const pages = [];
const outputs = new Map();
for (const file of files) {
  if (file === 'index.md') continue; // / redirects to getting-started; see src/pages/index.astro
  const raw = await readFile(path.join(source, 'docs', file), 'utf8');
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/);
  if (!match) continue; // no frontmatter: a working note, not a site page
  const unquote = (value) => value?.replace(/^(["'])(.*)\1$/, '$2');
  const title = unquote(match[1].match(/^title:\s*(.+)$/m)?.[1]);
  const order = Number(match[1].match(/^nav_order:\s*(\d+)$/m)?.[1]);
  // Optional: the search-result description and document title written in jerboa/docs.
  const description = unquote(match[1].match(/^description:\s*(.+)$/m)?.[1]);
  const seoTitle = unquote(match[1].match(/^seo_title:\s*(.+)$/m)?.[1]);
  if (!title || !order) throw new Error(`Missing navigation metadata: ${file}`);
  const slug = file.slice(0, -3);
  const url = `/${slug}/`;
  pages.push({ title, slug, url, order });
  const body = raw.slice(match[0].length)
    .replace(/## Table of contents\r?\n\{:[^\n]*\}\r?\n\r?\n1\. TOC\r?\n\{:toc\}\r?\n/, '')
    .replace(/\{%\s*link\s+([^\s]+)\s*%\}/g, (_, target) => {
      if (!files.includes(target)) throw new Error(`Unknown documentation link: ${target} in ${file}`);
      return target === 'index.md' ? '/' : `/${target.slice(0, -3)}/`;
    })
    .replace(/\{\{\s*site\.data\.versions\.(cli|kernel)\s*\}\}/g, (_, key) => versions[key])
    .split(/(```[\s\S]*?```)/g).map((part, index) => {
      if (index % 2) return part;
      // Kramdown dimension annotations are not HTML. Keep them as attributes
      // so the published snapshot still carries width and height.
      return part.replace(/!\[([^\]]*)\]\(([^)\s]+)\)\{:\s*([^}\n]*)\}/g, (all, alt, src, attrs) => {
        const width = attrs.match(/(?:^|\s)width=(?:"(\d+)"|'(\d+)'|(\d+))/)?.slice(1).find(Boolean);
        const height = attrs.match(/(?:^|\s)height=(?:"(\d+)"|'(\d+)'|(\d+))/)?.slice(1).find(Boolean);
        if (!width && !height) return all;
        return `<img src="${escapeAttr(src)}" alt="${escapeAttr(alt)}"${width ? ` width="${width}"` : ''}${height ? ` height="${height}"` : ''} />`;
      });
    }).join('')
    .replace(/\{:[^}\n]*\}/g, '')
    .replace(/^\[View on GitHub\]\(https:\/\/github\.com\/AitorConS\/jerboa\)[ \t]*\r?\n/gm, '');
  if (/\{%|\{\{\s*site\./.test(body)) throw new Error(`Unconverted Jekyll syntax: ${file}`);
  warnMissingAlt(file, body);
  const front = [
    '---',
    'layout: ../layouts/Docs.astro',
    `title: ${JSON.stringify(title)}`,
    description ? `description: ${JSON.stringify(description)}` : '',
    seoTitle ? `seoTitle: ${JSON.stringify(seoTitle)}` : '',
    `source: ${JSON.stringify(file)}`,
    '---',
  ].filter(Boolean).join('\n');
  outputs.set(path.join(destination, file), `${front}\n${marker}\n${body.trim()}\n`);
}
pages.sort((a, b) => a.order - b.order);
outputs.set(path.join(root, 'src/data/docs.json'), JSON.stringify({ versions, pages }, null, 2) + '\n');
await mkdir(destination, { recursive: true });
const stale = [];
for (const file of await readdir(destination)) {
  const target = path.join(destination, file);
  if (!outputs.has(target) && file.endsWith('.md') && (await readFile(target, 'utf8')).includes(marker)) stale.push(target);
}
let differences = stale.length;
const changedSlugs = new Set();
for (const [target, content] of outputs) {
  const previous = await readFile(target, 'utf8').catch(error => {
    if (error.code === 'ENOENT') return null;
    throw error;
  });
  if (previous === content) continue;
  differences++;
  if (check) console.error(`Out of sync: ${path.relative(root, target)}`);
  else await writeFile(target, content);
  if (path.dirname(target) === destination) changedSlugs.add(path.basename(target, '.md'));
}
for (const target of stale) {
  if (check) console.error(`Obsolete: ${path.relative(root, target)}`);
  else await unlink(target);
}
if (!check) await updateLastmod(changedSlugs, pages.map(page => page.slug));
if (check && differences) process.exitCode = 1;
console.log(`${pages.length} documentation pages ${check ? 'checked' : 'synchronized'} (CLI ${versions.cli}, kernel ${versions.kernel}); ${differences} ${check ? 'differences' : 'updates'}.`);
